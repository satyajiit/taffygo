package com.taffygo.browser.ui.feature.assistant

import com.taffygo.browser.ui.core.common.AppDispatchers
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.test.UnconfinedTestDispatcher

/**
 * One dispatcher for all three roles, so a test observes the whole of a
 * suspending call without a scheduler in the way.
 */
@OptIn(ExperimentalCoroutinesApi::class)
internal class TestDispatchers(
    private val dispatcher: CoroutineDispatcher = UnconfinedTestDispatcher(),
) : AppDispatchers {
    override val main: CoroutineDispatcher = dispatcher
    override val default: CoroutineDispatcher = dispatcher
    override val io: CoroutineDispatcher = dispatcher
}
