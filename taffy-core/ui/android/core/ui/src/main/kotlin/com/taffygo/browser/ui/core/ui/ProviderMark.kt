/**
 * The provider brand marks, and deliberately not part of [TaffyIcon].
 *
 * A Phosphor glyph is an icon this repository is licensed to use; a provider
 * mark is somebody's trademark, carried under a permitted use rather than a
 * licence. Decision `docs/decisions/0030-adopt-phosphor-icon-set.md` holds the
 * two to different provenance standards, so they are two objects in two files
 * with two provenance records — `core/ui/vendor/phosphor.txt` counts glyphs,
 * `core/ui/vendor/provider-marks.txt` checksums this file. Keeping them apart
 * is also what stops a mark added here from moving the Phosphor glyph count
 * that `tools/lib/vendored_assets.py` gates.
 *
 * The set does one job. All fifteen marks name a model provider on screen
 * SCR-404 and that vendor's own pages SCR-415 to SCR-417, and the provenance
 * file states that one permitted use. It used to state two: two further marks
 * named an account provider on the sign-in screen SCR-701, and they left with
 * that screen (decision
 * `docs/decisions/0201-the-first-run-asks-for-nothing-a-server-would-hold.md`).
 * A permitted use is not a licence, so a mark whose one permitted use is gone
 * has no standing to stay in the tree, and a trademark kept without one is a
 * defect no build can report.
 *
 * **Fifteen model-provider marks are here and one catalog vendor has none.** A
 * mark is vendored only when it can produce both an upstream URL and an
 * upstream checksum. Eight of the fifteen came from Simple Icons at the pin and
 * seven from lobe-icons at its pin, which still publishes what Simple Icons
 * does not, at the same URL-and-checksum bar. Every mark here names the vendor
 * whose own row draws it. Two rows once drew another name's mark — Google
 * Antigravity drew Gemini's until decision
 * `docs/decisions/0134-the-antigravity-row-is-withdrawn.md`, and Cloudflare
 * Workers AI drew Cloudflare's until decision
 * `docs/decisions/0214-the-cloudflare-row-leaves-and-retrieval-becomes-owed.md`
 * — and the Cloudflare mark left with its row, because that row was the whole
 * of its permitted use. The Gemini mark stayed, because it has its own row.
 * Z.AI has a mark at
 * lobe-icons and is deliberately not here — no owner-published document could
 * be found to argue a permitted use from, so its row draws a monogram, which
 * is the correct outcome rather than a gap.
 *
 * Every mark is drawn from its source file's own path data on that source's
 * 24-unit viewport, and none is ever redrawn or rebuilt from a different
 * outline. Most sources are one path; Cerebras is two and Together is three,
 * and each of those is carried as the source wrote it rather than merged into
 * one string. All fifteen are silhouettes and draw in a tint the caller
 * chooses, which is why this object needs no colour of its own: the exception
 * that did — an owner who specifies the mark's own ink and the ground behind
 * it — was the account pair, and it left with them.
 */
