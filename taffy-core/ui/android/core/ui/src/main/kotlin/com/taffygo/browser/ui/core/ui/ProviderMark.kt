/**
 * One vendored mark, built from the source file's own path data.
 *
 * `pathData` is a vararg because a source file is not always one path: most
 * marks are a single outline, but Cerebras ships two and Together ships three,
 * and each is added here exactly as its own path rather than concatenated into
 * one string. Concatenation would be a re-drawing decision — under either fill
 * rule the union of two outlines is not always what the source painted — and
 * decision 0030 does not permit a mark to be rebuilt from a different outline.
 * The count is asserted per mark in `ProviderMarkTest`.
 */
private fun mark(
    name: String,
    vararg pathData: String,
    fillType: PathFillType = PathFillType.NonZero,
): ImageVector =
    ImageVector.Builder(
        name = "ProviderMark.$name",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = Viewport,
        viewportHeight = Viewport,
    ).apply {
        pathData.forEach { data ->
            addPath(
                pathData = PathParser().parsePathString(data).toNodes(),
                fill = SolidColor(Color.Black),
                pathFillType = fillType,
            )
        }
    }.build()

